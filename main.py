
import os
from dotenv import load_dotenv
from google import genai
from google.genai import types

# Load environment variables
load_dotenv()

# Get API key
api_key = os.getenv("GEMINI_API_KEY")

# Initialize Gemini client only if API key exists
client = genai.Client(api_key=api_key) if api_key else None


class ResearchAgent:

    def __init__(self):
        self.name = "Research Assistant"

        self.instructions = """
        You are an intelligent AI Research Assistant.

        Your responsibilities:
        1. Understand the research topic.
        2. Explain the topic clearly.
        3. Organize the response into sections.
        4. Include applications, benefits and challenges.
        5. Provide a meaningful conclusion.

        Do not invent research citations or statistics.
        Mention when information needs verification.
        """

    # Demo mode: Generates a local sample report
    def demo_research(self, topic):

        return f"""
        RESEARCH TOPIC: {topic}

        NOTE: This is a locally generated DEMO report.
        It is not generated by an AI model.

        1. INTRODUCTION
        {topic} is an important area of study.
        It involves understanding its fundamental concepts,
        purpose and role in solving real-world problems.

        2. KEY CONCEPTS
        - Understanding the basic principles of {topic}.
        - Identifying its major components.
        - Exploring how it works and where it is applied.

        3. APPLICATIONS
        - Education and learning.
        - Business and industry.
        - Research and development.
        - Technology and innovation.

        4. BENEFITS
        - Helps solve practical problems.
        - Supports innovation.
        - Can improve efficiency and productivity.

        5. CHALLENGES
        - Technical limitations.
        - Implementation complexity.
        - Cost and resource requirements.
        - Need for continuous improvement.

        6. CONCLUSION
        {topic} offers opportunities for further exploration.
        Understanding its principles, applications and
        limitations is important for practical use.

        NOTE: This is template-based demonstration content.
        Verify facts using reliable sources before academic use.
        """

    # Live mode: Uses Gemini AI
    def live_research(self, topic):

        if client is None:
            raise ValueError("Gemini API key is not configured.")

        response = client.models.generate_content(
            model="gemini-3.8-flash",
            contents=f"Research this topic: {topic}",
            config=types.GenerateContentConfig(
                system_instruction=self.instructions,
                temperature=0.4
            )
        )

        if not response.text:
            raise RuntimeError("Gemini returned an empty response.")

        return response.text

    # Main research method
    def research(self, topic, mode):

        print(f"\n{self.name} is working...\n")

        if mode == "demo":
            print("Running in DEMO MODE...")
            return self.demo_research(topic)

        elif mode == "live":
            print("Connecting to Gemini AI...")

            try:
                result = self.live_research(topic)
                print("Gemini research completed!")
                return result

            except Exception as error:
                print(f"\nGemini API Error: {error}")
                print("\nSwitching to DEMO MODE...")
                return self.demo_research(topic)

        else:
            raise ValueError("Invalid mode selected.")


# Application entry point
if __name__ == "__main__":

    agent = ResearchAgent()

    print("=" * 45)
    print("       AI RESEARCH ASSISTANT")
    print("=" * 45)

    topic = input("\nEnter your research topic: ").strip()

    if not topic:
        print("Please enter a valid research topic.")
        raise SystemExit(1)

    print("\nSelect execution mode:")
    print("1. Live Mode (Gemini AI)")
    print("2. Demo Mode (Offline)")

    choice = input("\nEnter your choice (1/2): ").strip()

    if choice == "1":
        mode = "live"
    elif choice == "2":
        mode = "demo"
    else:
        print("Invalid choice. Please select 1 or 2.")
        raise SystemExit(1)

    result = agent.research(topic, mode)

    print("\n" + "=" * 45)
    print("           RESEARCH REPORT")
    print("=" * 45)
    print(result)
    print("\n" + "=" * 45)
